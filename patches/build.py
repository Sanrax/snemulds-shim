"""Build the version-pinned stable, DSP-1 and S-DD1 ARM7 touch patches."""
from pathlib import Path
import os, struct, subprocess
root = Path(__file__).resolve().parents[1]
prefix = Path(os.environ.get('WONDERFUL_TOOLCHAIN','/opt/wonderful'))/'toolchain/gcc-arm-none-eabi/bin/arm-none-eabi-'
out = root/'build/twl-patch'; out.mkdir(parents=True,exist_ok=True)
header = '/* Generated by patches/build.py; SPDX-License-Identifier: GPL-3.0-or-later */\n'
for name, delta, divide in [('twl', 0, 0xE4A8), ('dsp', -0xBC, 0xE1C0),
                             ('sdd1', -0x15C, 0xDFFC)]:
    elf = out/(name+'.elf')
    symbols = {'patchMain': 0x8AE8+delta, 'patchTask': 0x9248+delta,
               'cdcTouchRead': 0xA268+delta, 'cdcTouchInit': 0xA128+delta,
               'touchPenDown': 0x8A98+delta, '__aeabi_idiv': divide}
    flags = [f'-Wl,--defsym={key}=0x{0x03800000+value:x}' for key, value in symbols.items()]
    subprocess.run([str(prefix)+'gcc','-Os','-std=c11','-Wall','-Wextra','-Werror',
        '-mcpu=arm7tdmi','-marm','-ffreestanding','-fno-builtin','-fno-strict-aliasing',
        '-nostdlib','-Wl,--no-warn-rwx-segments',*flags,
        '-T'+str(root/'patches/twl_input.ld'),
        str(root/'patches/twl_input.c'),'-o',str(elf)],check=True)
    listing = subprocess.check_output([str(prefix)+'nm',str(elf)],text=True)
    address = {l.split()[-1]:int(l.split()[0],16) for l in listing.splitlines() if len(l.split())==3}
    for section in ['main','task']:
        binary = out/(name+'_'+section+'.bin')
        subprocess.run([str(prefix)+'objcopy','-O','binary','--only-section=.'+section,
                        str(elf),str(binary)],check=True)
        data = binary.read_bytes()
        header += f'static const uint32_t {name}_{section}[] = {{\n'
        for i in range(0,len(data),16):
            words = struct.unpack('<'+'I'*(len(data[i:i+16])//4),data[i:i+16])
            header += '    '+', '.join(f'0x{x:08X}' for x in words)+',\n'
        header += '};\n'
        print(name,section,len(data),'bytes')
    branch = 0xEA000000 | (((address['twlModeReady']-(0x038091D8+delta)-8)//4)&0xFFFFFF)
    header += f'#define {name.upper()}_MODE_BRANCH 0x{branch:08X}u\n'
target=root/'include/twl_input_generated.h'
if not target.exists() or target.read_text()!=header: target.write_text(header)
